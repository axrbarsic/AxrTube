import Foundation

public enum RussianTranscriptTranslationStage: Equatable, Sendable {
    case preparingAssets
    case translatingCurrentFragment
    case translatingAhead
    case translatingRemaining
}

public enum RussianTranscriptTranslationUpdate: Equatable, Sendable {
    case stage(RussianTranscriptTranslationStage)
    case translated(cues: [CaptionCue], stage: RussianTranscriptTranslationStage)
    case telemetry(RussianTranscriptTelemetry)
}

public enum RussianTranscriptCacheHit: String, Codable, Equatable, Sendable {
    case miss
    case partial
    case full
}

public struct RussianTranscriptTelemetry: Equatable, Sendable {
    public let timeToFirstRussian: TimeInterval?
    public let translatedAheadSeconds: TimeInterval
    public let translatedCueCount: Int
    public let totalCueCount: Int
    public let cacheHit: RussianTranscriptCacheHit
    public let resumeCount: Int

    public init(
        timeToFirstRussian: TimeInterval?,
        translatedAheadSeconds: TimeInterval,
        translatedCueCount: Int,
        totalCueCount: Int,
        cacheHit: RussianTranscriptCacheHit,
        resumeCount: Int
    ) {
        self.timeToFirstRussian = timeToFirstRussian
        self.translatedAheadSeconds = max(0, translatedAheadSeconds)
        self.translatedCueCount = translatedCueCount
        self.totalCueCount = totalCueCount
        self.cacheHit = cacheHit
        self.resumeCount = resumeCount
    }
}

public enum RussianTranscriptFailure: Error, Equatable, Sendable {
    case preparationDeclinedOrOffline
    case unsupportedLanguagePair
    case translationFailed
}

public struct RussianTranscriptRequest: Equatable, Sendable {
    public let videoID: String
    public let sourceTrackID: String
    public let sourceCues: [CaptionCue]
    public let sourceLanguageCode: String
    public let sourceHash: String
    public let playbackTime: TimeInterval

    public init(
        videoID: String,
        sourceTrackID: String,
        sourceCues: [CaptionCue],
        sourceLanguageCode: String,
        sourceHash: String,
        playbackTime: TimeInterval
    ) {
        self.videoID = videoID
        self.sourceTrackID = sourceTrackID
        self.sourceCues = CaptionTranscriptPolicy.normalizedCues(sourceCues)
        self.sourceLanguageCode = sourceLanguageCode
        self.sourceHash = sourceHash
        self.playbackTime = playbackTime
    }
}

public struct RussianTranscriptResult: Equatable, Sendable {
    public let cues: [CaptionCue]
    public let wasCached: Bool

    public init(cues: [CaptionCue], wasCached: Bool) {
        self.cues = CaptionTranscriptPolicy.normalizedCues(cues)
        self.wasCached = wasCached
    }
}

